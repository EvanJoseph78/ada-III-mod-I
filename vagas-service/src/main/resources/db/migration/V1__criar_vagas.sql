CREATE TABLE vagas (
    id_vaga BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vaga_id UUID NOT NULL UNIQUE,
    nome_vaga VARCHAR(255) NOT NULL,
    status VARCHAR(50) NOT NULL
);
CREATE TABLE requisitos_vaga (
    vaga_id BIGINT NOT NULL REFERENCES vagas(id_vaga),
    ordem INTEGER NOT NULL,
    tipo VARCHAR(50) NOT NULL,
    palavra_chave VARCHAR(255) NOT NULL,
    obrigatorio BOOLEAN NOT NULL,
    pontos INTEGER NOT NULL CHECK (pontos >= 0),
    meses_minimos INTEGER CHECK (meses_minimos >= 0),
    PRIMARY KEY (vaga_id, ordem)
);
